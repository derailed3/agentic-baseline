"""Copy the skills (.agents/skills/, the only hand-edited, tracked copy) to each mirror: the folder of an
agent tool that does not read .agents/skills/ itself (.claude/skills/ and the like, ignored by Git).

Usage: python scripts/deploy_skills.py            (write the mirrors)
       python scripts/deploy_skills.py --check    (exit 1 if a mirror differs; a missing one is reported)
       python scripts/deploy_skills.py --targets  (list the mirrors and which tool reads each)

Mirrors come from `mirrors:` in registry/skill-host.yaml. Each is listed in .gitignore, carries a marker
file, and is replaced as a whole, so a skill deleted from .agents/skills/ disappears from every mirror.
Only folders carrying the marker are ever replaced. The skill guard (scripts/skill_guard.py) runs this
after every checkout, merge, commit and rebase, so nobody has to remember. Standard library only.
"""
import filecmp
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = Path(".agents") / "skills"
HOST = Path("registry") / "skill-host.yaml"
MARKER = ".generated-copy"
IGNORE = ["__pycache__", ".pytest_cache", MARKER]


def mirrors(root: Path = ROOT) -> list[tuple[Path, str]]:
    """(folder, which tool reads it) for each `mirrors:` entry of the host file. Read without a YAML
    library so the guard runs on any Python: entries are `- path: <dir>` with an optional `reads:`."""
    text = (root / HOST).read_text(encoding="utf-8")
    block = re.search(r"^mirrors:\s*\n((?:[ \t]+.*\n?|\s*\n)*)", text, re.M)
    out = []
    if block:
        for m in re.finditer(r"-\s*path:\s*([^\s#]+)(?:\s*\n\s*reads:\s*(.+))?", block.group(1)):
            out.append((root / m.group(1).strip("'\""), (m.group(2) or "").strip().strip("'\"")))
    return out


def same(a: Path, b: Path) -> bool:
    cmp = filecmp.dircmp(a, b, ignore=IGNORE)
    if cmp.left_only or cmp.right_only or cmp.funny_files:
        return False
    _, mismatch, errors = filecmp.cmpfiles(a, b, cmp.common_files, shallow=False)
    if mismatch or errors:
        return False
    return all(same(a / d, b / d) for d in cmp.common_dirs)


def deploy(source: Path, target: Path) -> str:
    if target.exists():
        if not (target / MARKER).exists():
            raise SystemExit(f"refusing to replace {target}: it was not made by this script (no {MARKER})")
        if same(source, target):
            return "in sync"
        shutil.rmtree(target)
    shutil.copytree(source, target, ignore=shutil.ignore_patterns(*IGNORE))
    (target / MARKER).write_text("Generated by scripts/deploy_skills.py from .agents/skills/; edit there, never here.\n", encoding="utf-8")
    return "deployed"


def main(argv: list[str], root: Path = ROOT) -> int:
    source = root / SOURCE
    if "--targets" in argv:
        for target, reads in mirrors(root):
            print(f"{target.relative_to(root).as_posix():24} {reads}")
        return 0
    check = "--check" in argv
    status = 0
    for target, _ in mirrors(root):
        rel = target.relative_to(root).as_posix()
        if check:
            if not target.is_dir():
                print(f"missing   {rel} (run scripts/deploy_skills.py)")
            elif not same(source, target):
                print(f"stale     {rel} (run scripts/deploy_skills.py)")
                status = 1
            else:
                print(f"in sync   {rel}")
            continue
        print(f"{deploy(source, target):9} {rel}")
    return status


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
