"""Copy the canonical skills folder to where each agent tool looks.

Usage: python scripts/deploy_skills.py          (write the copies)
       python scripts/deploy_skills.py --check  (exit 1 if any existing copy differs; missing copies are reported)
Targets come from registry/skill-targets.txt, one folder per line. Each target is listed in
.gitignore: copies are generated, never committed or edited. Only folders carrying the marker
file written by this script are ever replaced. Standard library only.
"""
import filecmp
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "skills"
MARKER = ".generated-copy"
IGNORE = ["__pycache__", ".pytest_cache", MARKER]


def targets(root: Path = ROOT) -> list[Path]:
    lines = (root / "registry" / "skill-targets.txt").read_text(encoding="utf-8").splitlines()
    return [root / line.strip() for line in lines if line.strip() and not line.strip().startswith("#")]


def same(a: Path, b: Path) -> bool:
    cmp = filecmp.dircmp(a, b, ignore=IGNORE)
    if cmp.left_only or cmp.right_only or cmp.funny_files:
        return False
    _, mismatch, errors = filecmp.cmpfiles(a, b, cmp.common_files, shallow=False)
    if mismatch or errors:
        return False
    return all(same(a / d, b / d) for d in cmp.common_dirs)


def deploy(source: Path, target: Path) -> str:
    if target.exists():
        if not (target / MARKER).exists():
            raise SystemExit(f"refusing to replace {target}: it was not made by this script (no {MARKER})")
        if same(source, target):
            return "in sync"
        shutil.rmtree(target)
    shutil.copytree(source, target, ignore=shutil.ignore_patterns(*IGNORE))
    (target / MARKER).write_text("Generated by scripts/deploy_skills.py; edit skills/ instead.\n", encoding="utf-8")
    return "deployed"


def main(argv: list[str], root: Path = ROOT) -> int:
    source = root / "skills"
    check = "--check" in argv
    status = 0
    for target in targets(root):
        rel = target.relative_to(root).as_posix()
        if check:
            if not target.is_dir():
                print(f"missing   {rel} (run scripts/deploy_skills.py)")
            elif not same(source, target):
                print(f"stale     {rel} (run scripts/deploy_skills.py)")
                status = 1
            else:
                print(f"in sync   {rel}")
            continue
        print(f"{deploy(source, target):9} {rel}")
    return status


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
